for each row execute function public.invalidate_zoom_room_allocation_changes();

create or replace function public.invalidate_managed_zoom_room_changes()
returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  v_room_id uuid;
  v_allocation record;
begin
  v_room_id := case when tg_op = 'DELETE' then old.id else new.id end;
  perform public.bump_operational_invalidation('admin'::public.app_role, null, 'provider');
  perform public.bump_operational_invalidation('admin'::public.app_role, null, 'availability');
  perform public.bump_operational_invalidation('admin'::public.app_role, null, 'calendar');

  if tg_op = 'UPDATE' and (
    old.meeting_url is distinct from new.meeting_url
    or old.name is distinct from new.name
    or old.is_active is distinct from new.is_active
  ) then
    for v_allocation in
      select a.private_session_id, a.intensive_session_id,
        coalesce(pe.mentee_id, ig.mentee_id) as mentee_id,
        coalesce(ps.mentor_id, ins.mentor_id) as mentor_id
      from public.mentoring_zoom_room_allocations a
      left join public.private_mentoring_sessions ps on ps.id = a.private_session_id
      left join public.private_mentoring_enrollments pe on pe.id = ps.enrollment_id
      left join public.intensive_mentoring_sessions ins on ins.id = a.intensive_session_id
      left join public.intensive_mentoring_engagements ig on ig.id = ins.engagement_id
      where a.zoom_room_id = v_room_id and a.released_at is null and a.ends_at > now()
    loop
      if v_allocation.mentee_id is not null then
        perform public.bump_operational_invalidation('mentee'::public.app_role, v_allocation.mentee_id, 'provider');
        perform public.bump_operational_invalidation('mentee'::public.app_role, v_allocation.mentee_id, 'calendar');
        perform public.bump_operational_invalidation('mentee'::public.app_role, v_allocation.mentee_id, 'mentoring');
      end if;
      if v_allocation.mentor_id is not null then
        perform public.bump_operational_invalidation('mentor'::public.app_role, v_allocation.mentor_id, 'provider');
        perform public.bump_operational_invalidation('mentor'::public.app_role, v_allocation.mentor_id, 'calendar');
        perform public.bump_operational_invalidation('mentor'::public.app_role, v_allocation.mentor_id, 'mentor-dashboard');
      end if;
    end loop;
  end if;
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;


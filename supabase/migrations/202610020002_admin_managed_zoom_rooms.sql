      'intensive:session:' || new.session_id || ':calendar-failed:' || md5(coalesce(new.sync_error, '')));
  end if;
  return new;
end;
$$;

create or replace function public.invalidate_zoom_room_allocation_changes()
returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  v_private_session_id uuid;
  v_intensive_session_id uuid;
  v_mentee_id uuid;
  v_mentor_id uuid;
begin
  if tg_op = 'DELETE' then
    v_private_session_id := old.private_session_id;
    v_intensive_session_id := old.intensive_session_id;
  else
    v_private_session_id := new.private_session_id;
    v_intensive_session_id := new.intensive_session_id;
  end if;

  perform public.bump_operational_invalidation('admin'::public.app_role, null, 'provider');
  perform public.bump_operational_invalidation('admin'::public.app_role, null, 'calendar');
  perform public.bump_operational_invalidation('admin'::public.app_role, null, 'availability');

  if v_private_session_id is not null then
    select e.mentee_id, s.mentor_id into v_mentee_id, v_mentor_id
    from public.private_mentoring_sessions s
    join public.private_mentoring_enrollments e on e.id = s.enrollment_id
    where s.id = v_private_session_id;
  else
    select g.mentee_id, s.mentor_id into v_mentee_id, v_mentor_id
    from public.intensive_mentoring_sessions s
    join public.intensive_mentoring_engagements g on g.id = s.engagement_id
    where s.id = v_intensive_session_id;
  end if;

  if v_mentee_id is not null then
    perform public.bump_operational_invalidation('mentee'::public.app_role, v_mentee_id, 'provider');
    perform public.bump_operational_invalidation('mentee'::public.app_role, v_mentee_id, 'calendar');
    perform public.bump_operational_invalidation('mentee'::public.app_role, v_mentee_id, 'mentoring');
  end if;
  if v_mentor_id is not null then
    perform public.bump_operational_invalidation('mentor'::public.app_role, v_mentor_id, 'provider');
    perform public.bump_operational_invalidation('mentor'::public.app_role, v_mentor_id, 'calendar');
    perform public.bump_operational_invalidation('mentor'::public.app_role, v_mentor_id, 'mentor-dashboard');
  end if;
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

create trigger zoom_room_allocations_operational_invalidation

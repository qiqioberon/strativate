create or replace function public.admin_set_private_mentoring_session_status(p_session_id uuid, p_status text)
returns public.private_mentoring_sessions
language plpgsql security definer set search_path = '' as $$
declare v_session public.private_mentoring_sessions; v_from text;
begin
  if not public.is_admin() then raise exception 'Admin required' using errcode = '42501'; end if;
  if p_status not in ('completed', 'scheduled') then raise exception 'Unsupported status transition' using errcode = '22023'; end if;
  select * into v_session from public.private_mentoring_sessions where id = p_session_id for update;
  if not found then raise exception 'Private Mentoring session not found' using errcode = '22023'; end if;
  if v_session.status = p_status then return v_session; end if;
  if not ((v_session.status = 'scheduled' and p_status = 'completed') or (v_session.status = 'completed' and p_status = 'scheduled')) then
    raise exception 'Only scheduled -> completed or completed -> scheduled is allowed' using errcode = '22023';
  end if;
  if p_status = 'completed' and v_session.topic_status <> 'confirmed' then
    raise exception 'Resolve the session topic before completion' using errcode = '22023';
  end if;
  if p_status = 'scheduled' then
    perform public.reserve_mentoring_zoom_room(p_session_id, null, v_session.scheduled_start_at, v_session.scheduled_end_at, null);
  end if;
  v_from := v_session.status::text;
  update public.private_mentoring_sessions set status = p_status where id = p_session_id returning * into v_session;
  if p_status = 'completed' then
    update public.mentoring_zoom_room_allocations set released_at = coalesce(released_at, now()) where private_session_id = p_session_id;
  end if;
  insert into public.private_mentoring_session_status_events(session_id, from_status, to_status, actor_id)
  values(p_session_id, v_from, p_status, auth.uid());
  if p_status = 'scheduled' then
    update public.private_mentoring_enrollments set status = 'active' where id = v_session.enrollment_id;
  elsif not exists (
    select 1 from public.private_mentoring_sessions s
    where s.enrollment_id = v_session.enrollment_id and s.status not in ('completed', 'cancelled')
  ) then
    update public.private_mentoring_enrollments set status = 'completed' where id = v_session.enrollment_id;
  else
    update public.private_mentoring_enrollments set status = 'active' where id = v_session.enrollment_id;
  end if;
  return v_session;
end;
$$;

drop function if exists public.admin_schedule_intensive_mentoring_session(uuid, uuid, timestamptz);
create function public.admin_schedule_intensive_mentoring_session(
  p_session_id uuid,
  p_mentor_id uuid,
  p_scheduled_start_at timestamptz,
  p_zoom_room_id uuid default null
)
returns public.intensive_mentoring_sessions
language plpgsql security definer set search_path = '' as $$
declare
  v_session public.intensive_mentoring_sessions;
  v_eng public.intensive_mentoring_engagements;
  v_timezone text;
  v_end timestamptz;
  v_local_start timestamp;
  v_local_end timestamp;
  v_week_start date;
  v_day smallint;
  v_previous_status text;
begin
  if not public.is_admin() then raise exception 'Admin required' using errcode = '42501'; end if;
  if p_scheduled_start_at is null or p_scheduled_start_at <= now() then
    raise exception 'Future schedule required' using errcode = '22023';
  end if;
  select * into v_session from public.intensive_mentoring_sessions where id = p_session_id for update;
  if not found or v_session.status not in ('awaiting_scheduling', 'scheduled') or v_session.session_focus_id is null or v_session.resolved_topic is null then
    raise exception 'Resolved schedulable Intensive session required' using errcode = '22023';
  end if;
  select * into v_eng from public.intensive_mentoring_engagements where id = v_session.engagement_id;
  v_previous_status := v_session.status;
  select mp.timezone into v_timezone
  from public.mentor_profiles mp join public.profiles p on p.id = mp.user_id
  where mp.user_id = p_mentor_id and mp.is_active and p.role = 'mentor'::public.app_role;
  if not found then raise exception 'Active mentor required' using errcode = '22023'; end if;

  v_end := p_scheduled_start_at + make_interval(mins => v_session.duration_minutes);
  v_local_start := p_scheduled_start_at at time zone v_timezone;
  v_local_end := v_end at time zone v_timezone;
  v_week_start := date_trunc('week', v_local_start)::date;
  v_day := extract(isodow from v_local_start)::smallint;
  if v_local_end::date <> v_local_start::date or not exists (
    select 1 from public.mentor_availability_rules a
    where a.mentor_id = p_mentor_id and a.week_start_date = v_week_start and a.day_of_week = v_day
      and a.start_time <= v_local_start::time and a.end_time >= v_local_end::time
  ) then raise exception 'Selected slot is outside declared mentor availability' using errcode = '22023'; end if;

  if exists (
    select 1 from public.private_mentoring_sessions s
    where s.mentor_id = p_mentor_id and s.status in ('scheduled', 'completed')
      and tstzrange(s.scheduled_start_at, s.scheduled_end_at, '[)') && tstzrange(p_scheduled_start_at, v_end, '[)')
  ) or exists (
    select 1 from public.intensive_mentoring_sessions s
    where s.id <> p_session_id and s.mentor_id = p_mentor_id and s.status in ('scheduled', 'completed')
      and tstzrange(s.scheduled_start_at, s.scheduled_end_at, '[)') && tstzrange(p_scheduled_start_at, v_end, '[)')
  ) then raise exception 'Selected slot conflicts with another Strativate mentor session' using errcode = '23P01'; end if;

  if exists (
    select 1 from public.private_mentoring_sessions s
    join public.private_mentoring_enrollments e on e.id = s.enrollment_id
    where e.mentee_id = v_eng.mentee_id and s.status in ('scheduled', 'completed')
      and tstzrange(s.scheduled_start_at, s.scheduled_end_at, '[)') && tstzrange(p_scheduled_start_at, v_end, '[)')
  ) or exists (
    select 1 from public.intensive_mentoring_sessions s
    join public.intensive_mentoring_engagements e on e.id = s.engagement_id
    where s.id <> p_session_id and e.mentee_id = v_eng.mentee_id and s.status in ('scheduled', 'completed')
      and tstzrange(s.scheduled_start_at, s.scheduled_end_at, '[)') && tstzrange(p_scheduled_start_at, v_end, '[)')
  ) then raise exception 'Selected slot conflicts with another mentee session' using errcode = '23P01'; end if;

  perform public.reserve_mentoring_zoom_room(null, p_session_id, p_scheduled_start_at, v_end, p_zoom_room_id);
  update public.intensive_mentoring_sessions
  set mentor_id = p_mentor_id, scheduled_start_at = p_scheduled_start_at, scheduled_end_at = v_end, status = 'scheduled'
  where id = p_session_id returning * into v_session;
  insert into public.intensive_mentoring_session_calendar_integrations(session_id, organizer_user_id, sync_status, sync_error)
  values(p_session_id, auth.uid(), 'pending', null)
  on conflict(session_id) do update set
    organizer_user_id = coalesce(public.intensive_mentoring_session_calendar_integrations.organizer_user_id, excluded.organizer_user_id),
    sync_status = 'pending', sync_error = null;
  insert into public.intensive_mentoring_session_events(session_id, event_type, actor_user_id, from_status, to_status, metadata)
  values(p_session_id, case when v_previous_status = 'scheduled' then 'rescheduled' else 'scheduled' end, auth.uid(), v_previous_status, 'scheduled', jsonb_build_object('mentorId', p_mentor_id, 'start', p_scheduled_start_at, 'end', v_end));
  perform public.emit_notification(v_eng.mentee_id, 'mentee'::public.app_role, 'session_scheduled', 'Sesi Intensive Mentoring dijadwalkan', 'Sesi Intensive Mentoring kamu telah dijadwalkan.', 'intensive_mentoring_session', p_session_id::text, 'intensive:schedule:mentee:' || p_session_id::text || ':' || extract(epoch from p_scheduled_start_at)::bigint::text);
  perform public.emit_notification(p_mentor_id, 'mentor'::public.app_role, 'session_scheduled', 'Sesi Intensive Mentoring dijadwalkan', 'Sesi Intensive Mentoring baru telah dijadwalkan untuk kamu.', 'intensive_mentoring_session', p_session_id::text, 'intensive:schedule:mentor:' || p_session_id::text || ':' || extract(epoch from p_scheduled_start_at)::bigint::text);
  return v_session;
end;
$$;


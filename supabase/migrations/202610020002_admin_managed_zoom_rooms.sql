create or replace function public.admin_assign_mentoring_zoom_room(
  p_session_kind text,
  p_session_id uuid,
  p_zoom_room_id uuid
)
returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_start timestamptz;
  v_end timestamptz;
  v_status text;
  v_room public.mentoring_zoom_rooms;
  v_mentee_id uuid;
  v_mentor_id uuid;
begin
  if not public.is_admin() then raise exception 'Admin required' using errcode = '42501'; end if;
  if p_session_kind = 'private' then
    select s.scheduled_start_at, s.scheduled_end_at, s.status::text, e.mentee_id, s.mentor_id
    into v_start, v_end, v_status, v_mentee_id, v_mentor_id
    from public.private_mentoring_sessions s
    join public.private_mentoring_enrollments e on e.id = s.enrollment_id
    where s.id = p_session_id for update of s;
  elsif p_session_kind = 'intensive' then
    select s.scheduled_start_at, s.scheduled_end_at, s.status, g.mentee_id, s.mentor_id
    into v_start, v_end, v_status, v_mentee_id, v_mentor_id
    from public.intensive_mentoring_sessions s
    join public.intensive_mentoring_engagements g on g.id = s.engagement_id
    where s.id = p_session_id for update of s;
  else
    raise exception 'Jenis mentoring tidak valid' using errcode = '22023';
  end if;
  if not found then raise exception 'Sesi mentoring tidak ditemukan' using errcode = '22023'; end if;
  if v_status <> 'scheduled' or v_start is null or v_end is null then
    raise exception 'Hanya sesi terjadwal yang dapat mengganti Zoom room' using errcode = '22023';
  end if;

  if p_session_kind = 'private' then
    perform public.reserve_mentoring_zoom_room(p_session_id, null, v_start, v_end, p_zoom_room_id);
    update public.private_mentoring_session_calendar_integrations
    set sync_status = 'pending', sync_error = null
    where session_id = p_session_id;
  else
    perform public.reserve_mentoring_zoom_room(null, p_session_id, v_start, v_end, p_zoom_room_id);
    update public.intensive_mentoring_session_calendar_integrations
    set sync_status = 'pending', sync_error = null
    where session_id = p_session_id;
  end if;

  select * into v_room from public.mentoring_zoom_rooms where id = p_zoom_room_id;
  perform public.emit_notification(
    v_mentee_id,
    'mentee'::public.app_role,
    'meeting_url_changed',
    'Link Zoom sesi diperbarui',
    'Zoom room untuk sesi mentoring kamu telah diperbarui.',
    case when p_session_kind = 'private' then 'session' else 'intensive_mentoring_session' end,
    p_session_id::text,
    p_session_kind || ':zoom-room:' || p_session_id::text || ':' || p_zoom_room_id::text
  );
  if v_mentor_id is not null then
    perform public.emit_notification(
      v_mentor_id,
      'mentor'::public.app_role,
      'meeting_url_changed',
      'Link Zoom sesi diperbarui',
      'Zoom room untuk sesi mentoring yang kamu dampingi telah diperbarui.',
      case when p_session_kind = 'private' then 'session' else 'intensive_mentoring_session' end,
      p_session_id::text,
      p_session_kind || ':zoom-room:' || p_session_id::text || ':' || p_zoom_room_id::text || ':mentor'
    );
  end if;
  return jsonb_build_object('id', v_room.id, 'name', v_room.name, 'meetingUrl', v_room.meeting_url);
end;
$$;

create or replace function public.admin_get_mentoring_meeting_state(
  p_session_kind text,
  p_session_id uuid
)
returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_status text;
  v_start timestamptz;
  v_end timestamptz;
  v_room_id uuid;
  v_room_name text;
  v_room_url text;
  v_manual_url text;
  v_calendar_status text;
  v_calendar_error text;
  v_rooms jsonb := '[]'::jsonb;
begin
  if not public.is_admin() then raise exception 'Admin required' using errcode = '42501'; end if;
  if p_session_kind = 'private' then
    select s.status::text, s.scheduled_start_at, s.scheduled_end_at,
      a.zoom_room_id, r.name, r.meeting_url, ci.manual_meeting_url,
      coalesce(ci.sync_status, 'pending'), ci.sync_error
    into v_status, v_start, v_end, v_room_id, v_room_name, v_room_url, v_manual_url, v_calendar_status, v_calendar_error
    from public.private_mentoring_sessions s
    left join public.mentoring_zoom_room_allocations a on a.private_session_id = s.id
    left join public.mentoring_zoom_rooms r on r.id = a.zoom_room_id
    left join public.private_mentoring_session_calendar_integrations ci on ci.session_id = s.id
    where s.id = p_session_id;
  elsif p_session_kind = 'intensive' then
    select s.status, s.scheduled_start_at, s.scheduled_end_at,
      a.zoom_room_id, r.name, r.meeting_url, ci.manual_meeting_url,
      coalesce(ci.sync_status, 'pending'), ci.sync_error
    into v_status, v_start, v_end, v_room_id, v_room_name, v_room_url, v_manual_url, v_calendar_status, v_calendar_error
    from public.intensive_mentoring_sessions s
    left join public.mentoring_zoom_room_allocations a on a.intensive_session_id = s.id
    left join public.mentoring_zoom_rooms r on r.id = a.zoom_room_id
    left join public.intensive_mentoring_session_calendar_integrations ci on ci.session_id = s.id
    where s.id = p_session_id;
  else
    raise exception 'Jenis mentoring tidak valid' using errcode = '22023';
  end if;
  if not found then raise exception 'Sesi mentoring tidak ditemukan' using errcode = '22023'; end if;

  if v_status = 'scheduled' and v_start is not null and v_end is not null then
    select coalesce(jsonb_agg(jsonb_build_object(
      'id', r.id, 'name', r.name, 'meetingUrl', r.meeting_url, 'sortOrder', r.sort_order
    ) order by r.sort_order, r.name, r.id), '[]'::jsonb)
    into v_rooms
    from public.mentoring_zoom_rooms r
    where r.is_active
      and not exists (
        select 1 from public.mentoring_zoom_room_allocations a
        where a.zoom_room_id = r.id and a.released_at is null
          and not (
            a.private_session_id is not distinct from case when p_session_kind = 'private' then p_session_id end
            and a.intensive_session_id is not distinct from case when p_session_kind = 'intensive' then p_session_id end
          )
          and tstzrange(a.starts_at, a.ends_at, '[)') && tstzrange(v_start, v_end, '[)')
      );
  end if;

  return jsonb_build_object(
    'sessionId', p_session_id,
    'status', v_status,
    'assignedZoomRoomId', v_room_id,
    'assignedZoomRoomName', v_room_name,
    'managedMeetingUrl', case when v_status = 'scheduled' then v_room_url end,
    'manualMeetingUrl', case when v_status = 'scheduled' then v_manual_url end,
    'effectiveMeetingUrl', case when v_status = 'scheduled' then coalesce(v_manual_url, v_room_url) end,
    'calendarSyncStatus', v_calendar_status,
    'calendarSyncError', v_calendar_error,
    'availableZoomRooms', v_rooms
  );
end;
$$;


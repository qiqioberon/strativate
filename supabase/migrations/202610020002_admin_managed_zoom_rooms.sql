    perform public.emit_notification(v_mentee, 'mentee'::public.app_role, 'meeting_url_changed', 'Meeting link Intensive tersedia',
      'Meeting link sesi Intensive Mentoring tersedia atau berubah.', 'intensive_mentoring_session', new.session_id::text,
      'intensive:session:' || new.session_id || ':meeting:' || md5(v_effective) || ':mentee');
  end if;
  if new.sync_status = 'failed' and old.sync_status is distinct from 'failed' then
    perform public.emit_notification(null, 'admin'::public.app_role, 'calendar_failed', 'Google Calendar Intensive sync gagal',

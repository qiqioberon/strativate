-- Replace Zoom API provisioning with an Admin-managed pool of reusable Zoom rooms.
-- Existing provider columns remain as legacy audit data, but active runtime links resolve
-- from manual_meeting_url or the assigned managed room.

create table public.mentoring_zoom_rooms (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(btrim(name)) between 2 and 120),
  meeting_url text not null check (meeting_url ~* '^https://[^[:space:]]+$'),
  is_active boolean not null default true,
  sort_order integer not null default 0 check (sort_order >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index mentoring_zoom_rooms_normalized_url_key
  on public.mentoring_zoom_rooms (lower(regexp_replace(btrim(meeting_url), '/+$', '')));
create index mentoring_zoom_rooms_active_order_idx
  on public.mentoring_zoom_rooms (is_active desc, sort_order, name, id);

create trigger mentoring_zoom_rooms_touch_updated_at
before update on public.mentoring_zoom_rooms
for each row execute function public.touch_updated_at();

create table public.mentoring_zoom_room_allocations (
  id uuid primary key default gen_random_uuid(),
  zoom_room_id uuid not null references public.mentoring_zoom_rooms(id) on delete restrict,
  private_session_id uuid references public.private_mentoring_sessions(id) on delete restrict,
  intensive_session_id uuid references public.intensive_mentoring_sessions(id) on delete restrict,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  released_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (num_nonnulls(private_session_id, intensive_session_id) = 1),
  check (ends_at > starts_at)
);

create unique index mentoring_zoom_room_allocations_private_session_key
  on public.mentoring_zoom_room_allocations(private_session_id)
  where private_session_id is not null;
create unique index mentoring_zoom_room_allocations_intensive_session_key
  on public.mentoring_zoom_room_allocations(intensive_session_id)
  where intensive_session_id is not null;
create index mentoring_zoom_room_allocations_room_time_idx
  on public.mentoring_zoom_room_allocations(zoom_room_id, starts_at, ends_at)
  where released_at is null;

alter table public.mentoring_zoom_room_allocations
  add constraint mentoring_zoom_room_allocations_no_overlap
  exclude using gist (
    zoom_room_id extensions.gist_uuid_ops with =,
    tstzrange(starts_at, ends_at, '[)') with &&
  ) where (released_at is null);

create trigger mentoring_zoom_room_allocations_touch_updated_at
before update on public.mentoring_zoom_room_allocations
for each row execute function public.touch_updated_at();

alter table public.mentoring_zoom_rooms enable row level security;
alter table public.mentoring_zoom_room_allocations enable row level security;

create policy mentoring_zoom_rooms_admin_read
on public.mentoring_zoom_rooms for select to authenticated
using (public.is_admin());

create policy mentoring_zoom_room_allocations_admin_read
on public.mentoring_zoom_room_allocations for select to authenticated
using (public.is_admin());

revoke all on public.mentoring_zoom_rooms, public.mentoring_zoom_room_allocations
from public, anon, authenticated;
grant select on public.mentoring_zoom_rooms, public.mentoring_zoom_room_allocations
to authenticated;
grant all on public.mentoring_zoom_rooms, public.mentoring_zoom_room_allocations
to service_role;

-- Preserve every working upcoming URL generated by the retired provider integration.
update public.private_mentoring_session_calendar_integrations ci
set manual_meeting_url = coalesce(ci.manual_meeting_url, ci.provider_meeting_url)
from public.private_mentoring_sessions s
where s.id = ci.session_id
  and s.status = 'scheduled'
  and ci.provider_meeting_url is not null;

update public.intensive_mentoring_session_calendar_integrations ci
set manual_meeting_url = coalesce(ci.manual_meeting_url, ci.provider_meeting_url)
from public.intensive_mentoring_sessions s
where s.id = ci.session_id
  and s.status = 'scheduled'
  and ci.provider_meeting_url is not null;

create or replace function public.admin_list_mentoring_zoom_rooms()
returns table (
  id uuid,
  name text,
  meeting_url text,
  is_active boolean,
  sort_order integer,
  current_usage_count bigint,
  upcoming_usage_count bigint,
  next_usage_at timestamptz,
  created_at timestamptz,
  updated_at timestamptz
)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not public.is_admin() then raise exception 'Admin required' using errcode = '42501'; end if;
  return query
  select r.id, r.name, r.meeting_url, r.is_active, r.sort_order,
    count(a.id) filter (where a.released_at is null and a.starts_at <= now() and a.ends_at > now()),
    count(a.id) filter (where a.released_at is null and a.ends_at > now()),
    min(a.starts_at) filter (where a.released_at is null and a.ends_at > now()),
    r.created_at, r.updated_at
  from public.mentoring_zoom_rooms r
  left join public.mentoring_zoom_room_allocations a on a.zoom_room_id = r.id
  group by r.id
  order by r.sort_order, r.name, r.id;
end;
$$;

create or replace function public.admin_upsert_mentoring_zoom_room(
  p_id uuid,
  p_name text,
  p_meeting_url text,
  p_is_active boolean default true,
  p_sort_order integer default 0
)
returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_name text := nullif(btrim(coalesce(p_name, '')), '');
  v_url text := regexp_replace(btrim(coalesce(p_meeting_url, '')), '/+$', '');
  v_previous public.mentoring_zoom_rooms;
  v_room public.mentoring_zoom_rooms;
begin
  if not public.is_admin() then raise exception 'Admin required' using errcode = '42501'; end if;
  if v_name is null or char_length(v_name) not between 2 and 120 then
    raise exception 'Nama Zoom room wajib 2-120 karakter' using errcode = '22023';
  end if;
  if v_url !~* '^https://[^[:space:]]+$' then
    raise exception 'Zoom URL harus menggunakan HTTPS' using errcode = '22023';
  end if;
  if coalesce(p_sort_order, 0) < 0 then
    raise exception 'Urutan Zoom room tidak valid' using errcode = '22023';
  end if;

  if p_id is null then
    insert into public.mentoring_zoom_rooms(name, meeting_url, is_active, sort_order)
    values(v_name, v_url, coalesce(p_is_active, true), coalesce(p_sort_order, 0))
    returning * into v_room;
  else
    select * into v_previous from public.mentoring_zoom_rooms where id = p_id for update;
    if not found then raise exception 'Zoom room tidak ditemukan' using errcode = '22023'; end if;
    if v_previous.is_active and not coalesce(p_is_active, true) and exists (
      select 1 from public.mentoring_zoom_room_allocations a
      where a.zoom_room_id = p_id and a.released_at is null and a.ends_at > now()
    ) then
      raise exception 'Zoom room masih digunakan sesi aktif atau mendatang. Ganti room sesi terkait sebelum menonaktifkan.' using errcode = '23503';
    end if;
    update public.mentoring_zoom_rooms
    set name = v_name,
        meeting_url = v_url,
        is_active = coalesce(p_is_active, true),
        sort_order = coalesce(p_sort_order, 0)
    where id = p_id
    returning * into v_room;

    if v_previous.meeting_url is distinct from v_room.meeting_url then
      update public.private_mentoring_session_calendar_integrations ci
      set sync_status = 'pending', sync_error = null
      from public.mentoring_zoom_room_allocations a
      join public.private_mentoring_sessions s on s.id = a.private_session_id
      where a.zoom_room_id = v_room.id
        and a.released_at is null
        and a.ends_at > now()
        and s.status = 'scheduled'
        and ci.session_id = s.id;

      update public.intensive_mentoring_session_calendar_integrations ci
      set sync_status = 'pending', sync_error = null
      from public.mentoring_zoom_room_allocations a
      join public.intensive_mentoring_sessions s on s.id = a.intensive_session_id
      where a.zoom_room_id = v_room.id
        and a.released_at is null
        and a.ends_at > now()
        and s.status = 'scheduled'
        and ci.session_id = s.id;
    end if;
  end if;

  return jsonb_build_object(
    'room', to_jsonb(v_room),
    'urlChanged', p_id is not null and v_previous.meeting_url is distinct from v_room.meeting_url
  );
exception
  when unique_violation then
    raise exception 'Zoom URL sudah terdaftar' using errcode = '23505';
end;
$$;

create or replace function public.admin_delete_mentoring_zoom_room(p_id uuid)
returns uuid
language plpgsql security definer set search_path = '' as $$
begin
  if not public.is_admin() then raise exception 'Admin required' using errcode = '42501'; end if;
  if exists (select 1 from public.mentoring_zoom_room_allocations where zoom_room_id = p_id) then
    raise exception 'Zoom room memiliki riwayat sesi dan tidak dapat dihapus. Nonaktifkan room ini.' using errcode = '23503';
  end if;
  delete from public.mentoring_zoom_rooms where id = p_id;
  if not found then raise exception 'Zoom room tidak ditemukan' using errcode = '22023'; end if;
  return p_id;
end;
$$;

create or replace function public.admin_get_mentoring_zoom_room_pool(
  p_from timestamptz,
  p_to timestamptz,
  p_private_session_id uuid default null,
  p_intensive_session_id uuid default null
)
returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare v_result jsonb;
begin
  if not public.is_admin() then raise exception 'Admin required' using errcode = '42501'; end if;
  if p_from is null or p_to is null or p_to <= p_from then
    raise exception 'Rentang ketersediaan Zoom room tidak valid' using errcode = '22023';
  end if;
  select coalesce(jsonb_agg(jsonb_build_object(
    'id', r.id,
    'name', r.name,
    'meetingUrl', r.meeting_url,
    'sortOrder', r.sort_order,
    'busy', coalesce((
      select jsonb_agg(jsonb_build_object('start', a.starts_at, 'end', a.ends_at) order by a.starts_at)
      from public.mentoring_zoom_room_allocations a
      where a.zoom_room_id = r.id
        and a.released_at is null
        and not (
          a.private_session_id is not distinct from p_private_session_id
          and a.intensive_session_id is not distinct from p_intensive_session_id
        )
        and tstzrange(a.starts_at, a.ends_at, '[)') && tstzrange(p_from, p_to, '[)')
    ), '[]'::jsonb)
  ) order by r.sort_order, r.name, r.id), '[]'::jsonb)
  into v_result
  from public.mentoring_zoom_rooms r
  where r.is_active;
  return v_result;
end;
$$;

create or replace function public.reserve_mentoring_zoom_room(
  p_private_session_id uuid,
  p_intensive_session_id uuid,
  p_starts_at timestamptz,
  p_ends_at timestamptz,
  p_requested_room_id uuid default null
)
returns uuid
language plpgsql security definer set search_path = '' as $$
declare
  v_room_id uuid;
  v_existing_room_id uuid;
begin
  if num_nonnulls(p_private_session_id, p_intensive_session_id) <> 1 then
    raise exception 'Exactly one mentoring session is required' using errcode = '22023';
  end if;
  if p_starts_at is null or p_ends_at is null or p_ends_at <= p_starts_at then
    raise exception 'Jadwal sesi tidak valid' using errcode = '22023';
  end if;

  select a.zoom_room_id into v_existing_room_id
  from public.mentoring_zoom_room_allocations a
  where a.private_session_id is not distinct from p_private_session_id
    and a.intensive_session_id is not distinct from p_intensive_session_id;

  if p_requested_room_id is not null then
    select r.id into v_room_id
    from public.mentoring_zoom_rooms r
    where r.id = p_requested_room_id and r.is_active
    for update;
    if v_room_id is null then
      raise exception 'Zoom room tidak aktif atau tidak ditemukan' using errcode = '22023';
    end if;
    if exists (
      select 1 from public.mentoring_zoom_room_allocations a
      where a.zoom_room_id = v_room_id
        and a.released_at is null
        and not (
          a.private_session_id is not distinct from p_private_session_id
          and a.intensive_session_id is not distinct from p_intensive_session_id
        )
        and tstzrange(a.starts_at, a.ends_at, '[)') && tstzrange(p_starts_at, p_ends_at, '[)')
    ) then
      raise exception 'Zoom room baru saja dipakai sesi lain. Muat ulang dan pilih room lain.' using errcode = '23P01';
    end if;
  else
    if v_existing_room_id is not null then
      select r.id into v_room_id
      from public.mentoring_zoom_rooms r
      where r.id = v_existing_room_id and r.is_active
        and not exists (
          select 1 from public.mentoring_zoom_room_allocations a
          where a.zoom_room_id = r.id
            and a.released_at is null
            and not (
              a.private_session_id is not distinct from p_private_session_id
              and a.intensive_session_id is not distinct from p_intensive_session_id
            )
            and tstzrange(a.starts_at, a.ends_at, '[)') && tstzrange(p_starts_at, p_ends_at, '[)')
        )
      for update;
    end if;

    if v_room_id is null then
      select r.id into v_room_id
      from public.mentoring_zoom_rooms r
      where r.is_active
        and not exists (
          select 1 from public.mentoring_zoom_room_allocations a
          where a.zoom_room_id = r.id
            and a.released_at is null
            and not (
              a.private_session_id is not distinct from p_private_session_id
              and a.intensive_session_id is not distinct from p_intensive_session_id
            )
            and tstzrange(a.starts_at, a.ends_at, '[)') && tstzrange(p_starts_at, p_ends_at, '[)')
        )
      order by r.sort_order, r.name, r.id
      for update skip locked
      limit 1;
    end if;

    if v_room_id is null then
      if not exists (select 1 from public.mentoring_zoom_rooms where is_active) then
        raise exception 'Belum ada Zoom room aktif. Tambahkan link Zoom dari menu Admin → Zoom.' using errcode = 'P0001';
      end if;
      raise exception 'Semua Zoom room sedang terpakai pada jam ini. Muat ulang pilihan jadwal.' using errcode = '23P01';
    end if;
  end if;

  begin
    if p_private_session_id is not null then
      insert into public.mentoring_zoom_room_allocations(
        zoom_room_id, private_session_id, starts_at, ends_at, released_at
      ) values (
        v_room_id, p_private_session_id, p_starts_at, p_ends_at, null
      )
      on conflict (private_session_id) where private_session_id is not null
      do update set zoom_room_id = excluded.zoom_room_id,
                    starts_at = excluded.starts_at,
                    ends_at = excluded.ends_at,
                    released_at = null;
    else
      insert into public.mentoring_zoom_room_allocations(
        zoom_room_id, intensive_session_id, starts_at, ends_at, released_at
      ) values (
        v_room_id, p_intensive_session_id, p_starts_at, p_ends_at, null
      )
      on conflict (intensive_session_id) where intensive_session_id is not null
      do update set zoom_room_id = excluded.zoom_room_id,
                    starts_at = excluded.starts_at,
                    ends_at = excluded.ends_at,
                    released_at = null;
    end if;
  exception when exclusion_violation then
    raise exception 'Zoom room baru saja dipakai sesi lain. Muat ulang dan pilih room lain.' using errcode = '23P01';
  end;
  return v_room_id;
end;
$$;

create or replace function public.admin_get_private_mentoring_slot_context(p_session_id uuid)
returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare v_result jsonb;
begin
  if not public.is_admin() then raise exception 'Admin required' using errcode = '42501'; end if;
  select jsonb_build_object(
    'sessionId', s.id, 'status', s.status, 'topicStatus', s.topic_status,
    'focusName', coalesce(s.resolved_topic, f.name), 'resolvedTopic', s.resolved_topic,
    'requiredTierId', pkg.mentor_tier_id, 'durationMinutes', pkg.duration_minutes,
    'menteeId', e.mentee_id, 'purchasedSessions', e.purchased_sessions,
    'sessionNumber', s.session_number, 'primaryMentorRequired', e.purchased_sessions >= 5,
    'primaryMentorId', e.primary_mentor_id,
    'mentors', coalesce((
      select jsonb_agg(jsonb_build_object(
        'mentorId', mp.user_id,
        'mentorName', coalesce(nullif(btrim(concat_ws(' ', pp.first_name, pp.last_name)), ''), au.email),
        'tierId', mp.tier_id, 'active', mp.is_active, 'timezone', mp.timezone,
        'availability', coalesce((select jsonb_agg(jsonb_build_object(
          'start', (((a.week_start_date + (a.day_of_week - 1))::date + a.start_time) at time zone mp.timezone),
          'end', (((a.week_start_date + (a.day_of_week - 1))::date + a.end_time) at time zone mp.timezone)
        ) order by a.week_start_date, a.day_of_week, a.start_time)
          from public.mentor_availability_rules a
          where a.mentor_id = mp.user_id and a.week_start_date in (
            date_trunc('week', current_timestamp at time zone mp.timezone)::date,
            date_trunc('week', current_timestamp at time zone mp.timezone)::date + 7
          )), '[]'::jsonb),
        'strativate_busy', coalesce((
          select jsonb_agg(jsonb_build_object('start', busy.starts_at, 'end', busy.ends_at) order by busy.starts_at)
          from (
            select other.scheduled_start_at as starts_at, other.scheduled_end_at as ends_at
            from public.private_mentoring_sessions other
            where other.mentor_id = mp.user_id and other.id <> s.id
              and other.status in ('scheduled', 'completed') and other.scheduled_start_at is not null
            union all
            select other.scheduled_start_at, other.scheduled_end_at
            from public.intensive_mentoring_sessions other
            where other.mentor_id = mp.user_id and other.status in ('scheduled', 'completed')
              and other.scheduled_start_at is not null
          ) busy
        ), '[]'::jsonb)
      ) order by coalesce(pp.first_name, ''), coalesce(pp.last_name, ''), mp.user_id)
      from public.mentor_profiles mp
      join public.profiles pp on pp.id = mp.user_id and pp.role = 'mentor'::public.app_role
      join auth.users au on au.id = mp.user_id
      where mp.tier_id = pkg.mentor_tier_id and mp.is_active
        and (e.purchased_sessions < 5 or mp.user_id = e.primary_mentor_id)
    ), '[]'::jsonb)
  ) into v_result
  from public.private_mentoring_sessions s
  join public.private_mentoring_enrollments e on e.id = s.enrollment_id
  join public.private_mentoring_packages pkg on pkg.id = e.package_id
  left join public.private_mentoring_session_focuses f on f.id = s.session_focus_id
  where s.id = p_session_id;
  if v_result is null then raise exception 'Private Mentoring session not found' using errcode = '22023'; end if;
  return v_result;
end;
$$;

drop function if exists public.admin_schedule_private_mentoring_session(uuid, uuid, timestamptz);
create function public.admin_schedule_private_mentoring_session(
  p_session_id uuid,
  p_mentor_id uuid,
  p_scheduled_start_at timestamptz,
  p_zoom_room_id uuid default null
)
returns public.private_mentoring_sessions
language plpgsql security definer set search_path = '' as $$
declare
  v_session public.private_mentoring_sessions;
  v_required_tier uuid;
  v_duration integer;
  v_purchased integer;
  v_primary uuid;
  v_mentor_tier uuid;
  v_mentor_active boolean;
  v_timezone text;
  v_end timestamptz;
  v_local_start timestamp;
  v_local_end timestamp;
  v_local_date date;
  v_week_start date;
  v_day smallint;
begin
  if not public.is_admin() then raise exception 'Admin required' using errcode = '42501'; end if;
  if p_scheduled_start_at is null or p_scheduled_start_at <= now() then
    raise exception 'Schedule must be in the future' using errcode = '22023';
  end if;
  select * into v_session from public.private_mentoring_sessions where id = p_session_id for update;
  if not found then raise exception 'Private Mentoring session not found' using errcode = '22023'; end if;

  select pkg.mentor_tier_id, pkg.duration_minutes, e.purchased_sessions, e.primary_mentor_id
  into v_required_tier, v_duration, v_purchased, v_primary
  from public.private_mentoring_enrollments e
  join public.private_mentoring_packages pkg on pkg.id = e.package_id
  where e.id = v_session.enrollment_id;

  if v_session.topic_status <> 'confirmed' or v_session.session_focus_id is null or v_session.resolved_topic is null then
    raise exception 'Session topic must be confirmed before scheduling' using errcode = '22023';
  end if;
  if v_session.status not in ('awaiting_scheduling', 'scheduled') then
    raise exception 'Session is not schedulable' using errcode = '22023';
  end if;
  if v_purchased >= 5 and v_primary is null then
    raise exception 'Set the enrollment primary mentor before scheduling' using errcode = '22023';
  end if;
  if v_purchased >= 5 and p_mentor_id is distinct from v_primary then
    raise exception 'This package must use the enrollment primary mentor' using errcode = '22023';
  end if;

  select mp.tier_id, mp.is_active, mp.timezone
  into v_mentor_tier, v_mentor_active, v_timezone
  from public.mentor_profiles mp
  join public.profiles p on p.id = mp.user_id and p.role = 'mentor'::public.app_role
  where mp.user_id = p_mentor_id;
  if not found or not v_mentor_active then raise exception 'Active mentor required' using errcode = '22023'; end if;
  if v_mentor_tier is distinct from v_required_tier then
    raise exception 'Mentor tier does not match purchased package' using errcode = '22023';
  end if;

  v_end := p_scheduled_start_at + make_interval(mins => v_duration);
  v_local_start := p_scheduled_start_at at time zone v_timezone;
  v_local_end := v_end at time zone v_timezone;
  v_local_date := v_local_start::date;
  v_week_start := date_trunc('week', v_local_start)::date;
  v_day := extract(isodow from v_local_start)::smallint;
  if v_local_end::date <> v_local_date or not exists (
    select 1 from public.mentor_availability_rules a
    where a.mentor_id = p_mentor_id and a.week_start_date = v_week_start and a.day_of_week = v_day
      and a.start_time <= v_local_start::time and a.end_time >= v_local_end::time
  ) then
    raise exception 'Selected slot is outside declared mentor availability' using errcode = '22023';
  end if;

  if exists (
    select 1 from public.private_mentoring_sessions other
    where other.id <> p_session_id and other.mentor_id = p_mentor_id and other.status in ('scheduled', 'completed')
      and tstzrange(other.scheduled_start_at, other.scheduled_end_at, '[)') && tstzrange(p_scheduled_start_at, v_end, '[)')
  ) or exists (
    select 1 from public.intensive_mentoring_sessions other
    where other.mentor_id = p_mentor_id and other.status in ('scheduled', 'completed')
      and tstzrange(other.scheduled_start_at, other.scheduled_end_at, '[)') && tstzrange(p_scheduled_start_at, v_end, '[)')
  ) then
    raise exception 'Selected slot conflicts with another Strativate mentor session' using errcode = '23P01';
  end if;

  perform public.reserve_mentoring_zoom_room(p_session_id, null, p_scheduled_start_at, v_end, p_zoom_room_id);

  begin
    update public.private_mentoring_sessions
    set mentor_id = p_mentor_id,
        scheduled_start_at = p_scheduled_start_at,
        scheduled_end_at = v_end,
        status = 'scheduled'
    where id = p_session_id
    returning * into v_session;
